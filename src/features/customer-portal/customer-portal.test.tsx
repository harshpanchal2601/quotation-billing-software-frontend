const identity: api.PortalIdentity = { id: 8, companyId: 42, company: { name: 'QA Customer India', companyCode: 'COMP-0042' }, name: 'QA named contact', email: 'contact@example.invalid', contactId: 9, revokedAt: null, _count: { invitations: 1, grants: 1 }, invitations: [{ id: 10, expiresAt: '2099-11-12T12:00:00.000Z', consumedAt: null, revokedAt: null }], grants: [{ id: 11, quotationId: 74, quotation: { quotationNumber: 'QUOTE-74', revisionNumber: 2 }, invoiceId: null, invoice: null, salesOrderId: null, salesOrder: null, expiresAt: '2099-11-25T12:00:00.000Z', allowDecision: true, revokedAt: null, acceptances: [{ id: 12, decision: 'ACCEPTED', actorName: 'QA named contact', revisionNumber: 2, createdAt: '2026-11-11T12:00:00.000Z', snapshotHash: 'b'.repeat(64) }] }] };
function renderAccess(route = '/portal-access') {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: 0 }, mutations: { retry: false } } });
  const ui = () => <QueryClientProvider client={client}><NotificationProvider><MemoryRouter initialEntries={[route]}><PortalAccessPage /></MemoryRouter></NotificationProvider></QueryClientProvider>;
  const result = render(ui());
  return { ...result, refreshActor: () => result.rerender(ui()) };
}
